                "        memory = self.transformer.encoder(src_emb, src_key_padding_mask=src_padding_mask)\n",
                "\n",
                "        ys = torch.full((batch_size, 1), self.bos_idx, dtype=torch.long, device=device)\n",
                "        finished = torch.zeros(batch_size, dtype=torch.bool, device=device)\n",
                "\n",
                "        for _ in range(max_len):\n",
                "            tgt_mask = nn.Transformer.generate_square_subsequent_mask(ys.size(1), device=device).bool()\n",
