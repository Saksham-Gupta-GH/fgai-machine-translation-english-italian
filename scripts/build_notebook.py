                "            out = self.transformer.decoder(\n",
                "                tgt_emb,\n",
                "                memory,\n",
                "                tgt_mask=tgt_mask,\n",
                "                memory_key_padding_mask=src_padding_mask,\n",
                "            )\n",
                "            logits = self.generator(out[:, -1, :])\n",
                "            next_token = torch.argmax(logits, dim=-1, keepdim=True)\n",
